/** Быстрые подсказки для чата (главная). */
export const CHAT_PROMPTS = [
  {
    label: "Что надеть малышу на прогулку?",
    prompt:
      "Хочу выйти погулять с малышом, во что его одеть под сегодняшнюю погоду?",
  },
  {
    label: "Как спит мой малыш",
    prompt:
      "Посмотри дневник сна и скажи, нормально ли малыш спит для своего возраста",
  },
  {
    label: "Вести прикорм",
    prompt:
      "Хочу вести дневник прикорма: что пробовали, сколько и как отреагировал малыш",
  },
] as const;

export type ChatChip = { label: string; prompt: string };

/** Подсказки под возраст малыша. Без даты рождения — общий набор. */
export function chipsForBaby(birthDate?: string, now = new Date()): ChatChip[] {
  const base: ChatChip[] = [...CHAT_PROMPTS];
  if (!birthDate?.trim()) return base;
  const born = new Date(`${birthDate}T12:00:00`);
  if (Number.isNaN(born.getTime())) return base;
  const months =
    (now.getFullYear() - born.getFullYear()) * 12 +
    (now.getMonth() - born.getMonth());
  if (months < 4) {
    return [
      {
        label: "Нормально ли спит ночью?",
        prompt:
          "Посмотри дневник сна и скажи, похоже ли это на обычный сон для возраста малыша. Без диагноза.",
      },
      {
        label: "Хватает ли кормлений?",
        prompt:
          "По дневникам кормления скажи, не мало ли за сегодня. Если данных нет, спроси, что записать.",
      },
      base[0],
    ];
  }
  if (months < 8) {
    return [
      {
        label: "Регресс сна, что делать?",
        prompt:
          "Малышу около полугода. Если в дневнике сна ночи стали рваными, объясни про регресс спокойно и что попробовать сегодня.",
      },
      {
        label: "Что уже можно в прикорм?",
        prompt:
          "По возрасту и дневнику прикорма подскажи, какой следующий продукт попробовать. Учти аллергии из профиля.",
      },
      base[0],
    ];
  }
  return [
    {
      label: "Что умеет в этом возрасте?",
      prompt:
        "Коротко: что обычно умеет малыш в его возрасте и что из этого не обязательно. Без запугивания.",
    },
    {
      label: "Режим на завтра",
      prompt:
        "По дневникам сна и еды предложи мягкий режим на завтра. Не жёсткое расписание.",
    },
    base[0],
  ];
}
