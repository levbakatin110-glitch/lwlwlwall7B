export function otherRecipes(slug: string, limit = 6): Recipe[] {
  return RECIPES.filter((r) => r.slug !== slug).slice(0, limit);
}

export function formatTime(min: number): string {
  if (min < 60) return `${min} мин`;
  const h = Math.floor(min / 60);
  const m = min % 60;
  return m ? `${h} ч ${m} мин` : `${h} ч`;
}
